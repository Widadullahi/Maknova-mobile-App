'use client';

import { useMemo } from 'react';
import { arrayFrom } from '../../../lib/api';
import { ageLabel, labelize } from '../../../lib/format';
import { useManagerSession } from '../../../lib/auth';
import { useResource } from '../../../lib/useResource';
import { DashboardShell } from '../../../components/DashboardShell';
import { DataTable } from '../../../components/DataTable';

export default function VisitorsPage() {
  const { token, status } = useManagerSession();
  const { data } = useResource('/visitor-passes', token, { enabled: status === 'ready' });

  const visitors = useMemo(
    () =>
      arrayFrom(data, 'passes', 'visitorPasses').map((item) => ({
        id: item.id,
        code: item.code || item.passCode || '-',
        visitor: item.visitorName || item.name || 'Unknown visitor',
        host: item.hostName || item.requestedBy || 'Unknown host',
        status: labelize(item.status),
        age: ageLabel(item.createdAt || item.updatedAt),
      })),
    [data],
  );

  return (
    <DashboardShell title="Visitors" subtitle="Visitor passes and gate activity across your estates.">
      <DataTable
        title="Visitor Passes"
        subtitle="QR and PIN visitor activity."
        columns={[
          { key: 'code', label: 'Code' },
          { key: 'visitor', label: 'Visitor' },
          { key: 'host', label: 'Host' },
          { key: 'status', label: 'Status', pill: true },
          { key: 'age', label: 'Updated' },
        ]}
        rows={visitors}
        emptyTitle="No visitor passes"
        emptyBody="Passes generated by your residents or security team will appear here."
      />
    </DashboardShell>
  );
}
